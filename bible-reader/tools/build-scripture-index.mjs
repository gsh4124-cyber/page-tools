// Rebuild from the pinned provider checkout; no network requests during builds.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../',import.meta.url));
const providerRevision='9586bd8228a747962df1ee8692730422fb7eb2ec';
const provider=process.argv.find(arg=>arg.startsWith('--provider='))?.slice(11);
assert(provider,'Pass --provider=/path/to/midvash/bible-data checkout');
assert.equal(execFileSync('git',['-C',provider,'rev-parse','HEAD'],{encoding:'utf8'}).trim(),providerRevision);
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const context=vm.createContext({document:{querySelector:()=>null}});
vm.runInContext(app.slice(0,app.indexOf('const $=')),context);
vm.runInContext(fs.readFileSync(path.join(root,'extra-translations.js'),'utf8'),context);
const {books,translations}=vm.runInContext('({books:BOOKS,translations:TRANSLATIONS})',context);
assert.equal(vm.runInContext('MIDVASH_REVISION',context),providerRevision);
vm.runInContext(app.slice(app.indexOf('function normalizeMidvash('),app.indexOf('function getBookStructure(')),context);
const index={},provenance={provider:'https://github.com/midvash/bible-data',provider_revision:providerRevision,translations:{}},fixtures={};
const hash=value=>createHash('sha256').update(JSON.stringify(value)).digest('hex');
for(const [id,tr] of Object.entries(translations)){
  const all=[];let chapterCount=0,verseCount=0,sparseChapters=0;
  for(const book of books){
    const file=id==='krv1961'?path.join(root,'scripture/krv1961',book.file+'.json'):path.join(provider,'versions',tr.lang,tr.slug,'books',book.osis+'.json');
    const raw=JSON.parse(fs.readFileSync(file,'utf8'));
    const data=id==='krv1961'?raw:context.normalizeMidvash(raw);
    const structure=data.chapters.map(ch=>({chapter:Number(ch.chapter),verses:ch.verses.map(v=>Number(v.verse))}));
    assert(structure.length>0,`${id}/${book.osis}: no chapters`);
    assert.equal(new Set(structure.map(ch=>ch.chapter)).size,structure.length);
    for(const ch of structure){
      assert(Number.isInteger(ch.chapter)&&ch.chapter>0);
      assert(ch.verses.length>0&&ch.verses.every(n=>Number.isInteger(n)&&n>0));
      assert(ch.verses.every((n,i)=>i===0||n>ch.verses[i-1]));
      chapterCount++;verseCount+=ch.verses.length;
    }
    all.push(structure.map((ch,i)=>{
      if(ch.chapter===i+1&&ch.verses.every((n,j)=>n===j+1))return ch.verses.length;
      sparseChapters++;return ch;
    }));
    if(id!=='krv1961'){
      fixtures[id]??={lang:tr.lang,slug:tr.slug};
      if(book.osis==='John')fixtures[id].seed={chapters:raw.chapters.slice(0,3).map(ch=>({...ch,verses:ch.verses.slice(0,1)}))};
      if(book.osis==='Acts')fixtures[id].acts8=structure.find(ch=>ch.chapter===8).verses;
    }
  }
  index[id]=all;
  provenance.translations[id]={books:all.length,chapters:chapterCount,verses:verseCount,sparse_chapters:sparseChapters,structure_sha256:hash(all)};
}
const files={
  'scripture-index.js':'// Generated by tools/build-scripture-index.mjs; exact per-translation numbering.\n// Integers encode contiguous 1..N verses; objects preserve skipped verse numbers.\nwindow.BibleChapterIndex='+JSON.stringify(index)+';\n',
  'tools/scripture-index-sources.json':JSON.stringify(provenance,null,2)+'\n',
  'tools/fixtures/picker-translations.json':JSON.stringify(fixtures,null,2)+'\n'
};
for(const [name,content] of Object.entries(files)){
  const target=path.join(root,name);
  if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8').replaceAll('\r\n','\n'),content,`${name}: regenerate from pinned source`);
  else {fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,content);}
}
console.log(`Scripture index ${process.argv.includes('--check')?'verified':'generated'}: ${Object.keys(index).length} translations, ${books.length} books each, ${Buffer.byteLength(files['scripture-index.js'])} bytes.`);
